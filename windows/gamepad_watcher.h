#ifndef FLUTTER_PLUGIN_JUST_GAMEPADS_GAMEPAD_WATCHER_H_
#define FLUTTER_PLUGIN_JUST_GAMEPADS_GAMEPAD_WATCHER_H_

#include <windows.gaming.input.h>
#include <wrl/client.h>

#include <flutter/encodable_value.h>

#include <atomic>
#include <functional>
#include <mutex>
#include <string>
#include <thread>
#include <unordered_map>
#include <vector>

namespace just_gamepads {

// Owns the Windows.Gaming.Input subscriptions and the ~60Hz polling thread,
// emitting one flutter::EncodableValue event map per connect/disconnect/state
// change via a callback. Uses the classic WinRT ABI (raw COM interfaces from
// <windows.gaming.input.h>, Microsoft::WRL::ComPtr) rather than C++/WinRT
// projections deliberately: projections (winrt::Windows::Gaming::Input::*)
// need headers generated by cppwinrt.exe via the C++/WinRT NuGet package,
// which the standard Flutter Windows plugin CMake template doesn't set up —
// the ABI headers ship with the plain Windows SDK, no extra build-system
// wiring required.
//
// Two independent controller sources, matching the wire protocol's two
// message shapes (see gamepad_wire_protocol.dart):
//  - IGamepad (the "Gamepad" class): any XInput-compatible pad (Xbox
//    360/One/Series, most 8BitDo units in X-input mode). Fully semantic —
//    GamepadReading's buttons/axes map 1:1 to just_inputs' standard layout,
//    sent as the wire protocol's 'axes'/'buttons' (pre-normalized) shape.
//  - IRawGameController: the fallback for everything else — critically,
//    PS4/PS5 pads are NOT XInput devices and only ever appear here. Exposes
//    HardwareVendorId/HardwareProductId (sent up for the shared Dart
//    classifier) and raw button/axis arrays (sent as the wire protocol's
//    'rawAxes'/'rawButtons' shape for the shared Dart generic-HID mapper).
//    Correlated against IGamepad via RawGameController::FromGameController
//    to avoid double-reporting devices visible on both APIs.
class GamepadWatcher {
 public:
  using EventCallback = std::function<void(flutter::EncodableValue)>;

  GamepadWatcher();
  ~GamepadWatcher();

  GamepadWatcher(const GamepadWatcher&) = delete;
  GamepadWatcher& operator=(const GamepadWatcher&) = delete;

  // Starts WinRT subscriptions + the polling thread; idempotent. Events are
  // delivered on whatever thread calls this class's internals (the polling
  // thread for state, the WinRT event-callback thread for connect/
  // disconnect) — callers needing UI-thread delivery must marshal
  // themselves (see JustGamepadsPlugin's message-only window).
  void Start(EventCallback on_event);

  // Stops the polling thread and unregisters all WinRT event handlers.
  void Stop();

 private:
  struct TrackedGamepad {
    std::string id;
    Microsoft::WRL::ComPtr<ABI::Windows::Gaming::Input::IGamepad> gamepad;
  };
  struct TrackedRawController {
    std::string id;
    Microsoft::WRL::ComPtr<ABI::Windows::Gaming::Input::IRawGameController>
        raw_controller;
    UINT32 button_count = 0;
    UINT32 axis_count = 0;
    UINT32 switch_count = 0;
    // Used by PollRawController to special-case Sony's DualShock4/DualSense
    // axis layout quirk (see the comment there) — kept per-tracked-device
    // rather than re-queried every poll.
    UINT16 vendor_id = 0;
    UINT16 product_id = 0;
  };

  void PollLoop();
  void PollGamepad(const TrackedGamepad& tracked);
  void PollRawController(const TrackedRawController& tracked);
  void EmitConnected(const std::string& id, const std::wstring& name,
                      int vendor_id, int product_id);
  void EmitDisconnected(const std::string& id);

  // True while `raw_controller` corresponds to an already-tracked IGamepad
  // (per RawGameController::FromGameController) — such raw controllers are
  // skipped entirely so a single physical Xbox-compatible pad isn't reported
  // twice.
  bool IsCorrelatedWithGamepad(
      ABI::Windows::Gaming::Input::IRawGameController* raw_controller);

  EventCallback on_event_;
  std::atomic<bool> running_{false};
  std::thread poll_thread_;

  Microsoft::WRL::ComPtr<ABI::Windows::Gaming::Input::IGamepadStatics>
      gamepad_statics_;
  Microsoft::WRL::ComPtr<
      ABI::Windows::Gaming::Input::IRawGameControllerStatics>
      raw_statics_;

  EventRegistrationToken gamepad_added_token_{};
  EventRegistrationToken gamepad_removed_token_{};
  EventRegistrationToken raw_added_token_{};
  EventRegistrationToken raw_removed_token_{};

  // Keyed by the raw interface pointer's identity (stable for the lifetime
  // of one connection — WinRT hands back the same interface pointer to our
  // Added/Removed handlers for a given physical connection) rather than any
  // hardware serial, since none is reliably available across all
  // controller types.
  std::mutex controllers_mutex_;
  std::unordered_map<void*, TrackedGamepad> gamepads_;
  std::unordered_map<void*, TrackedRawController> raw_controllers_;
};

}  // namespace just_gamepads

#endif  // FLUTTER_PLUGIN_JUST_GAMEPADS_GAMEPAD_WATCHER_H_
